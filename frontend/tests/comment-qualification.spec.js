const { test, expect } = require('@playwright/test')
const { registrationConsent } = require('./helpers/registration')
const path = require('node:path')
const api = process.env.API_TEST_URL || 'http://127.0.0.1:18080/api'

test('注册不答题，评论需达到90分，80分重答后返回评论且资格持久', async ({ page, request }) => {
  test.setTimeout(90000)
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  const username = 'examui' + Date.now().toString(36), password = 'ExamBrowser123!'
  const registered = await request.post(api + '/auth/register', { data: { username, password, nickname: '评论答题成员', ...await registrationConsent(request, api) } })
  expect(registered.ok()).toBeTruthy()
  const member = (await registered.json()).data, headers = { Authorization: 'Bearer ' + member.token }
  expect(member.user.commentQualification.passed).toBe(false)
  const created = await request.post(api + '/dreams', { headers, data: { title: '评论资格 ' + Date.now(), category: 'LIFE', helpType: 'COMPANY' } })
  expect(created.ok()).toBeTruthy()
  const dream = (await created.json()).data, endpoint = api + '/dreams/' + dream.id
  await page.goto('/#/pages/auth/index')
  await page.locator('.wd-input').filter({ hasText: '账号' }).locator('input').fill(username)
  await page.locator('.wd-input').filter({ hasText: '密码' }).locator('input').fill(password)
  await page.locator('.wd-button').filter({ hasText: /^登录圆梦$/ }).click()
  await expect(page).not.toHaveURL(/auth\/index/)
  await page.goto('/#/pages/dream/detail?id=' + dream.id)
  await page.locator('.dream-reactions .wd-button').filter({ hasText: /^精神支持/ }).click()
  await page.locator('.dream-reactions .wd-button').filter({ hasText: /^评论/ }).click()
  const comments = page.locator('.dream-comments')
  await expect(comments.locator('textarea')).toBeDisabled()
  await comments.locator('.wd-button').filter({ hasText: /^去答题$/ }).click()
  await expect(page).toHaveURL(/admission\/index/)
  await page.setViewportSize({ width: 320, height: 844 })
  const groups = page.locator('.wd-radio-group'), correct = [1, 2, 0, 1, 2, 0, 1, 2, 0, 1]
  await expect(groups).toHaveCount(10)
  expect(await page.locator('.wd-radio__label').evaluateAll(labels => labels.every(el => el.scrollWidth <= el.clientWidth + 1 && el.scrollHeight <= el.clientHeight + 1))).toBeTruthy()
  await page.locator('.wd-button').filter({ hasText: /^提交答案$/ }).click()
  await expect(groups).toHaveCount(10)
  for (let i = 0; i < correct.length; i++) await groups.nth(i).locator('.wd-radio').nth(i < 2 ? (correct[i] + 1) % 3 : correct[i]).click()
  await page.locator('.wd-button').filter({ hasText: /^提交答案$/ }).click()
  await expect(page.getByText('80 分，未通过', { exact: true })).toBeVisible()
  await expect(page.getByText('80 分，未通过', { exact: true })).toBeInViewport()
  expect((await request.post(endpoint + '/comments', { headers, data: { content: '未通过的评论', qualified: true } })).status()).toBe(403)
  await expect(page.locator('.uni-toast')).not.toBeVisible()
  await page.screenshot({ path: path.resolve(__dirname, '../../.runtime/comment-exam-80.png'), animations: 'disabled' })
  await groups.first().locator('.wd-radio').nth(correct[0]).click()
  await page.locator('.wd-button').filter({ hasText: /^重新提交$/ }).click()
  await expect(page.getByText('已获得评论资格', { exact: true })).toBeVisible()
  await expect(page.getByText('90 分', { exact: true })).toBeVisible()
  await expect(page.getByText('90 分', { exact: true })).toBeInViewport()
  await page.screenshot({ path: path.resolve(__dirname, '../../.runtime/comment-exam-90.png'), animations: 'disabled' })
  await page.locator('.wd-button').filter({ hasText: /^返回评论$/ }).click()
  await expect(page).toHaveURL(/dream\/detail/)
  await expect(comments.locator('textarea')).toBeEnabled()
  await comments.locator('textarea').fill('通过问答后，认真交流')
  await comments.locator('.wd-button').filter({ hasText: /^发表评论$/ }).click()
  await expect(comments.locator('.comment-card').filter({ hasText: '通过问答后，认真交流' })).toContainText('精神支持')
  await page.reload()
  await page.locator('.dream-reactions .wd-button').filter({ hasText: /^评论/ }).click()
  await expect(comments.locator('textarea')).toBeEnabled()
  await expect(comments.locator('.wd-button').filter({ hasText: /^去答题$/ })).toHaveCount(0)
  expect((await (await request.get(api + '/admission/status', { headers })).json()).data.passed).toBe(true)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  expect(errors).toEqual([])
})
