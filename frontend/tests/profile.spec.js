const { test, expect } = require('@playwright/test')
const { registrationConsent } = require('./helpers/registration')
const fs = require('node:fs')
const path = require('node:path')
const api = process.env.API_TEST_URL || 'http://127.0.0.1:18080/api'

test('个人资料：默认头像、上传重试、保存持久化、取消和恢复默认', async ({ page, request }) => {
  test.setTimeout(90000)
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  const username = 'profile' + Date.now().toString(36), password = 'ProfileBrowser123!'
  const registered = await request.post(api + '/auth/register', { data: { username, password, nickname: '头像测试成员', ...await registrationConsent(request, api) } })
  expect(registered.ok()).toBeTruthy()
  const member = (await registered.json()).data
  const headers = { Authorization: 'Bearer ' + member.token }
  const runtime = path.resolve(__dirname, '../../.runtime')
  fs.mkdirSync(runtime, { recursive: true })
  fs.appendFileSync(path.join(runtime, 'profile-e2e-fixtures.jsonl'), JSON.stringify({ id: member.user.id, username }) + '\n')
  const me = async () => (await (await request.get(api + '/me', { headers })).json()).data
  const button = text => page.locator('.wd-button').filter({ hasText: new RegExp('^' + text + '$'), visible: true })
  const popup = page.locator('.wd-popup').filter({ visible: true })
  async function login() {
    await page.goto('/#/pages/auth/index')
    await page.locator('.wd-input').filter({ hasText: '账号' }).locator('input').fill(username)
    await page.locator('.wd-input').filter({ hasText: '密码' }).locator('input').fill(password)
    await button('登录圆梦').click()
    await expect(page).not.toHaveURL(/auth\/index/)
    await page.goto('/#/pages/me/index')
  }
  await login()
  await expect(page.locator('.user-avatar .wd-icon-user-circle').first()).toBeVisible()
  await button('编辑资料').click()
  const image = await page.evaluate(() => {
    const canvas = document.createElement('canvas'); canvas.width = 160; canvas.height = 160
    const ctx = canvas.getContext('2d'); ctx.fillStyle = '#e5f2ee'; ctx.fillRect(0, 0, 160, 160)
    ctx.fillStyle = '#21877a'; ctx.beginPath(); ctx.arc(80, 60, 25, 0, Math.PI * 2); ctx.fill()
    ctx.beginPath(); ctx.arc(80, 140, 50, Math.PI, Math.PI * 2); ctx.fill()
    return canvas.toDataURL('image/png').split(',')[1]
  })
  let failOnce = true
  await page.route('**/api/media', route => {
    if (failOnce) { failOnce = false; return route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ code: 503, message: '上传中断，请重试' }) }) }
    return route.continue()
  })
  const chooser = page.waitForEvent('filechooser')
  await button('更换头像').click()
  await (await chooser).setFiles({ name: 'avatar.png', mimeType: 'image/png', buffer: Buffer.from(image, 'base64') })
  await expect(page.getByText('上传中断，请重试', { exact: true })).toBeVisible()
  await expect(button('保存')).toHaveClass(/is-disabled/)
  await button('重试').click()
  await expect(popup.locator('.user-avatar .wd-img')).toBeVisible()
  await expect(button('保存')).not.toHaveClass(/is-disabled/)
  await popup.locator('.wd-input').filter({ hasText: '昵称' }).locator('input').fill('西宁的小梦想')
  await popup.locator('.wd-input').filter({ hasText: '城市' }).locator('input').fill('西宁')
  await popup.locator('.wd-textarea').filter({ hasText: '关于我' }).locator('textarea').fill('喜欢摄影和旅行')
  await popup.locator('.wd-textarea').filter({ hasText: '我能帮助' }).locator('textarea').fill('摄影、修图')
  await page.screenshot({ path: path.join(runtime, 'profile-edit.png'), animations: 'disabled' })
  await button('保存').click()
  await expect(popup).toHaveCount(0)
  await expect(page.getByText('西宁的小梦想', { exact: true })).toBeVisible()
  const saved = await me()
  expect(saved).toMatchObject({ nickname: '西宁的小梦想', city: '西宁', bio: '喜欢摄影和旅行', skills: '摄影、修图' })
  expect(saved.avatarId).toMatch(/^[a-f0-9-]{36}$/)
  await page.reload()
  await expect(page.locator('.user-avatar .wd-img').first()).toBeVisible()
  await page.screenshot({ path: path.join(runtime, 'profile-saved.png'), animations: 'disabled' })
  await button('编辑资料').click()
  await button('恢复默认').click()
  await expect(popup.locator('.wd-icon-user-circle')).toBeVisible()
  await popup.locator('.wd-popup__close').click()
  expect((await me()).avatarId).toBe(saved.avatarId)
  await page.goto('/#/pages/profile/index?id=' + member.user.id)
  await expect(page.getByText('西宁的小梦想', { exact: true })).toBeVisible()
  await expect(page.locator('.user-avatar .wd-img')).toBeVisible()
  // 断图回退到默认头像，避免出现空白头像。
  await page.route('**' + saved.avatarUrl, route => route.fulfill({ status: 404, body: '' }))
  await page.reload()
  await expect(page.locator('.user-avatar .wd-icon-user-circle')).toBeVisible()
  await page.unroute('**' + saved.avatarUrl)
  await page.evaluate(() => localStorage.clear())
  await login()
  await expect(page.getByText('西宁的小梦想', { exact: true })).toBeVisible()
  await expect(page.locator('.user-avatar .wd-img').first()).toBeVisible()
  await button('编辑资料').click()
  await button('恢复默认').click()
  await button('保存').click()
  await expect(popup).toHaveCount(0)
  await page.reload()
  await expect(page.locator('.user-avatar .wd-icon-user-circle').first()).toBeVisible()
  expect((await me()).avatarUrl).toBe('')
  expect((await me()).nickname).toBe('西宁的小梦想')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  expect(errors).toEqual([])
})
