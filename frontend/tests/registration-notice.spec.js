const { test, expect } = require('@playwright/test')
const path = require('node:path')

test('注册声明可阅读全文，加载失败禁止注册，版本更新后重新确认', async ({ page }) => {
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  let loads = 0
  await page.route('**/api/legal/registration-notice', async route => {
    loads++
    if (loads === 1) return route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ code: 503, message: '声明暂不可用' }) })
    await route.continue()
  })
  await page.goto('/#/pages/auth/index')
  await page.locator('.auth-alternative .wd-button').filter({ hasText: /^注册账号$/ }).click()
  await expect(page).toHaveURL(/auth\/register/)
  const panel = page.locator('.registration-notice')
  await expect(panel).toContainText('声明暂不可用')
  await expect(page.locator('.wd-radio-group')).toHaveCount(0)
  const submit = page.locator('.wd-button').filter({ hasText: /^注册账号$/ })
  await expect(submit).toHaveClass(/is-disabled/)
  await expect(panel.locator('.wd-checkbox')).toHaveCount(0)
  await panel.locator('.wd-button').filter({ hasText: /^重新加载声明$/ }).click()
  const consent = panel.locator('.wd-checkbox')
  await expect(consent).not.toHaveClass(/is-checked/)
  await expect(consent).toHaveClass(/is-disabled/)
  await panel.locator('.wd-button').filter({ hasText: /^查看完整声明$/ }).click()
  const popup = page.locator('.registration-notice-popup')
  await expect(popup).toBeVisible()
  await expect(popup).toContainText('六、责任边界与法定权利')
  await expect(popup).toContainText('人身损害')
  await expect(popup).toContainText('青海老铁软件有限公司')
  await popup.locator('.wd-button').filter({ hasText: /^阅读完成$/ }).click()
  await expect(consent).not.toHaveClass(/is-checked/)
  await page.locator('.wd-input').filter({ hasText: '账号' }).locator('input').fill('notice' + Date.now().toString(36))
  await page.locator('.wd-input').filter({ hasText: '密码' }).locator('input').fill('NoticeBrowser123!')
  await page.locator('.wd-input').filter({ hasText: '昵称' }).locator('input').fill('声明测试成员')
  await consent.click(); await expect(submit).not.toHaveClass(/is-disabled/)
  // 模拟页面打开期间发布了新文本；后端版本校验单独由集成测试覆盖。
  await page.route('**/api/auth/register', route => route.fulfill({ status: 412, contentType: 'application/json', body: JSON.stringify({ code: 412, message: '声明已更新，请重新阅读并同意' }) }), { times: 1 })
  await submit.click()
  await expect.poll(() => loads).toBe(3)
  await expect(consent).not.toHaveClass(/is-checked/)
  await expect(submit).toHaveClass(/is-disabled/)
  await expect(consent).toHaveClass(/is-disabled/)
  await expect(page.locator('.wd-input').filter({ hasText: '昵称' }).locator('input')).toHaveValue('声明测试成员')
  await panel.scrollIntoViewIfNeeded()
  await page.screenshot({ path: path.resolve(__dirname, '../../.runtime/registration-notice.png'), animations: 'disabled' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await panel.locator('.wd-button').filter({ hasText: /^查看完整声明$/ }).click()
  await popup.locator('.wd-button').filter({ hasText: /^阅读完成$/ }).click()
  await consent.click()
  await submit.click()
  await expect(page).not.toHaveURL(/pages\/auth\//)
  await page.goto('/#/pages/me/index')
  await page.getByText('免责声明与线下交流风险告知', { exact: true }).click()
  await expect(page).toHaveURL(/legal\/notice/)
  await expect(page.locator('.notice-document')).toContainText('1499058156@qq.com')
  expect(errors).toEqual([])
})
