async function createMember(request, prefix) {
  const username = prefix + Date.now().toString(36)
  const res = await request.post(api + '/auth/register', { data: { username, password, nickname: prefix + '成员', ...await registrationConsent(request, api) } })
  expect(res.ok()).toBeTruthy()
  const data = (await res.json()).data
  await passCommentExam(request, api, { Authorization: 'Bearer ' + data.token })
  return { ...data, username, headers: { Authorization: 'Bearer ' + data.token } }
}
async function login(page, member) {
  await page.goto('/#/pages/auth/index')
  await page.locator('.wd-input').filter({ hasText: '账号' }).locator('input').fill(member.username)
  await page.locator('.wd-input').filter({ hasText: '密码' }).locator('input').fill(password)
  await page.locator('.wd-button').filter({ hasText: /^登录圆梦$/ }).click()
  await expect(page).not.toHaveURL(/auth\/index/)
}
async function dream(request, member, anonymous) {
  const res = await request.post(api + '/dreams', { headers: member.headers, data: { title: '互动验证 ' + Date.now(), story: '我想学会摄影。', category: 'CREATION', helpType: 'SKILL', anonymous } })
  expect(res.ok()).toBeTruthy(); return (await res.json()).data
}

