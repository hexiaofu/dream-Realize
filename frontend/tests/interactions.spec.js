test('后台评论下架恢复、作者删除和受限账号', async ({ page, request }) => {
  test.skip(!adminName || !adminPassword, '需要独立测试管理员账号')
  test.setTimeout(90000)
  const member = await createMember(request, 'socialmod'), item = await dream(request, member, false)
  const endpoint = api + '/dreams/' + item.id
  expect((await request.put(endpoint + '/reaction', { headers: member.headers, data: { reaction: 'SUPPORT' } })).ok()).toBeTruthy()
  await request.post(endpoint + '/comments', { headers: member.headers, data: { content: '后台评论复核 ' + item.id } })
  const comment = (await (await request.get(endpoint + '/comments')).json()).data.items[0]
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto(adminUrl)
  await page.locator('.el-form-item').filter({ hasText: '管理员账号' }).locator('input').fill(adminName)
  await page.locator('.el-form-item').filter({ hasText: /^密码/ }).locator('input').fill(adminPassword)
  await page.getByRole('button', { name: '登录后台', exact: true }).click()
  await page.locator('.el-radio-button').filter({ hasText: /^评论$/ }).click()
  await page.locator('.filters .el-form-item').filter({ hasText: '关键词' }).locator('input').fill(item.title)
  await page.getByRole('button', { name: '查询', exact: true }).click()
  const row = page.locator('.el-table__body-wrapper tr').filter({ hasText: item.title }).first()
  await expect(row).toContainText(comment.content)
  await row.getByRole('button', { name: '查看', exact: true }).click()
  const drawer = page.getByRole('dialog', { name: '内容详情' })
  await expect(drawer.locator('.content')).toHaveText(comment.content)
  async function act(button, reason) {
    await drawer.getByRole('button', { name: button, exact: true }).click()
    const dialog = page.locator('.el-dialog').filter({ visible: true })
    await dialog.locator('textarea').fill(reason)
    await dialog.getByRole('button', { name: '确认处理', exact: true }).click()
    await expect(dialog).not.toBeVisible()
  }
  await act('下架内容', 'E2E：评论下架')
  expect((await (await request.get(endpoint)).json()).data.commentCount).toBe(0)
  expect((await (await request.get(endpoint + '/comments')).json()).data.items).toEqual([])
  await act('恢复内容', 'E2E：评论恢复')
  expect((await (await request.get(endpoint)).json()).data.commentCount).toBe(1)
  await request.delete(endpoint + '/comments/' + comment.id, { headers: member.headers })
  await page.reload()
  await page.locator('.el-radio-button').filter({ hasText: /^评论$/ }).click()
  const deleted = page.locator('.el-table__body-wrapper tr').filter({ hasText: comment.content }).first()
  await expect(deleted).toContainText('作者已删除')
  await expect(deleted.getByRole('button', { name: '恢复', exact: true })).toHaveCount(0)
  const restriction = await page.request.patch(adminUrl + '/api/admin/members/' + member.user.id + '/restriction', { headers: { 'X-Admin-Request': '1' }, data: { mode: 'READ_ONLY', durationHours: 24, expectedRevision: 0, reason: 'E2E：评论限发' } })
  expect(restriction.ok()).toBeTruthy()
  expect((await request.post(endpoint + '/comments', { headers: member.headers, data: { content: '限制后发表评论' } })).status()).toBe(403)
  expect((await request.put(endpoint + '/reaction', { headers: member.headers, data: { reaction: 'SUPPORT' } })).status()).toBe(403)
  await page.getByRole('menuitem', { name: '操作日志' }).click()
  await expect(page.locator('.el-table__body-wrapper tr').filter({ hasText: '评论 #' + comment.id }).filter({ hasText: 'E2E：评论下架' })).toBeVisible()
  await page.getByRole('button', { name: '退出登录', exact: true }).click()
})
