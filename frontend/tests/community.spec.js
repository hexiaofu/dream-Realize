test('图片视频：失败重试、移除、草稿恢复、匿名发布和进展播放', async ({ page, request }) => {
  test.setTimeout(90000)
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  const owner = await createMember(request, 'media')
  await login(page, owner.username)
  await page.goto('/#/pages/publish/index')
  const media = await page.evaluate(async () => {
    const canvas = document.createElement('canvas'); canvas.width = 240; canvas.height = 160
    const context = canvas.getContext('2d'); context.fillStyle = '#238478'; context.fillRect(0, 0, 240, 160)
    context.fillStyle = '#ffffff'; context.font = '24px sans-serif'; context.fillText('Dream video', 32, 85)
    const image = canvas.toDataURL('image/png').split(',')[1]
    const stream = canvas.captureStream(10), chunks = []
    const recorder = new MediaRecorder(stream, { mimeType: 'video/webm;codecs=vp8' })
    recorder.ondataavailable = event => chunks.push(event.data)
    const stopped = new Promise(resolve => { recorder.onstop = resolve })
    recorder.start()
    await new Promise(resolve => setTimeout(resolve, 650)); context.fillRect(5, 5, 20, 20)
    await new Promise(resolve => setTimeout(resolve, 650)); recorder.stop(); await stopped
    stream.getTracks().forEach(track => track.stop())
    return { image, video: Array.from(new Uint8Array(await new Blob(chunks, { type: 'video/webm' }).arrayBuffer())) }
  })
  const image = { name: 'dream.png', mimeType: 'image/png', buffer: Buffer.from(media.image, 'base64') }
  const video = { name: 'dream.webm', mimeType: 'video/webm', buffer: Buffer.from(media.video) }
  async function choose(index, file) {
    const chooser = page.waitForEvent('filechooser')
    await page.locator('.wd-upload').filter({ visible: true }).nth(index).locator('.wd-upload__evoke').click()
    await (await chooser).setFiles(file)
  }
  let first = true
  await page.route('**/api/media', route => {
    if (first) { first = false; return route.fulfill({ status: 503, contentType: 'application/json', body: '{"code":503,"message":"测试网络中断"}' }) }
    return route.continue()
  })
  await choose(0, image)
  await expect(page.getByText('有附件上传失败', { exact: true })).toBeVisible()
  await expect(page.locator('.wd-button').filter({ hasText: '请先完成附件上传' })).toHaveClass(/is-disabled/)
  await page.locator('.wd-button').filter({ hasText: /^重试上传$/ }).click()
  await expect(page.locator('.wd-upload__mask')).toHaveCount(0)
  await choose(0, image)
  await expect(page.locator('.wd-upload__mask')).toHaveCount(0)
  await expect(page.locator('.wd-upload').first().locator('.wd-upload__preview')).toHaveCount(2)
  const removed = page.waitForResponse(response => response.request().method() === 'DELETE' && response.url().includes('/api/media/'))
  await page.locator('.wd-upload').first().locator('.wd-upload__close').last().click()
  expect((await removed).ok()).toBeTruthy()
  await choose(1, video)
  await expect(page.locator('.wd-upload__mask')).toHaveCount(0)
  await expect(page.locator('.wd-upload__preview')).toHaveCount(2)
  await page.reload()
  await expect(page.locator('.wd-upload__preview')).toHaveCount(2)
  const title = '用图片视频记录梦想 ' + Date.now()
  await page.locator('.wd-input').filter({ hasText: '一句话心愿' }).locator('input').fill(title)
  await page.locator('.wd-switch').click()
  await page.locator('.wd-button').filter({ hasText: /^发布我的梦想$/ }).click()
  await expect(page).toHaveURL(/dream\/detail\?id=/)
  await expect(page.getByText('匿名梦想家', { exact: true })).toBeVisible()
  const renderedVideo = page.locator('.wd-card video').first()
  await expect(renderedVideo).toBeVisible()
  await expect.poll(() => renderedVideo.evaluate(video => video.readyState)).toBeGreaterThan(1)
  await renderedVideo.evaluate(async video => { video.muted = true; await video.play() })
  await expect.poll(() => renderedVideo.evaluate(video => video.currentTime)).toBeGreaterThan(0)
  await page.reload()
  await expect(page.locator('.wd-card .wd-img')).toHaveCount(1)
  await page.locator('.wd-button').filter({ hasText: /^记录新进展$/ }).click()
  await page.locator('.wd-textarea').filter({ hasText: '新的进展' }).locator('textarea').fill('新的创作已经完成，留下照片和视频。')
  await choose(0, image)
  await choose(1, video)
  await expect(page.locator('.wd-upload__mask')).toHaveCount(0)
  await page.locator('.wd-button').filter({ hasText: /^保存这段足迹$/ }).click()
  const progress = page.locator('.wd-card').filter({ hasText: '新的创作已经完成，留下照片和视频。' })
  await expect(progress.locator('.wd-img')).toHaveCount(1)
  await expect(progress.locator('video')).toBeVisible()
  await expect.poll(() => progress.locator('video').evaluate(video => video.readyState)).toBeGreaterThan(1)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  expect(errors).toEqual([])
})
